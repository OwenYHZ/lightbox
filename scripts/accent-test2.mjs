import { chromium } from "playwright-core";
import http from "node:http";
import path from "node:path";
import fs from "node:fs";
const dist = "E:\\code\\dshCode\\Lightbox\\dist";
const out = "E:\\code\\dshCode\\Lightbox\\shots\\live";
const MIME = { ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8", ".glb": "model/gltf-binary" };
const server = http.createServer((req, res) => {
  const url = decodeURIComponent((req.url || "/").split("?")[0]);
  let file = path.join(dist, url === "/" ? "index.html" : url);
  if (!fs.existsSync(file) || fs.statSync(file).isDirectory()) file = path.join(dist, "index.html");
  res.writeHead(200, { "Content-Type": MIME[path.extname(file)] || "application/octet-stream" });
  fs.createReadStream(file).pipe(res);
});
await new Promise((r) => server.listen(4221, "127.0.0.1", r));
const browser = await chromium.launch({ channel: "chrome", headless: true, args: ["--enable-unsafe-swiftshader"] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: "light", locale: "zh-CN" });
const page = await ctx.newPage();
await page.goto("http://127.0.0.1:4221/", { waitUntil: "networkidle" });
await page.waitForTimeout(600);
const read = () => page.evaluate(() => ({ accent: document.documentElement.dataset.accent, h: getComputedStyle(document.documentElement).getPropertyValue("--accent-h").trim(), bg: getComputedStyle(document.body).backgroundColor }));
const before = await read();
await page.click("#themeBtn");
await page.waitForTimeout(250);
await page.click('[data-accent-id="celadon"]');
await page.waitForTimeout(600);
const after = await read();
await page.screenshot({ path: path.join(out, "accent-celadon-fixed.jpg"), type: "jpeg", quality: 80 });
console.log(JSON.stringify({ before, after }));
await browser.close();
server.close();
process.exit(0);
